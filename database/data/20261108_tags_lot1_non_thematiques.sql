DECLARE problem text;
BEGIN
  SELECT string_agg(b.label, ' | ') INTO problem FROM non_thematic_batch b
    WHERE (SELECT count(*) FROM public.periods p WHERE p.label_fr = b.label) <> 1;
  IF problem IS NOT NULL THEN RAISE EXCEPTION 'Libellé absent ou ambigu, lot refusé : %', problem; END IF;
  SELECT string_agg(b.label, ' | ') INTO problem FROM non_thematic_batch b
    JOIN public.periods p ON p.label_fr = b.label JOIN public.period_tags t ON t.period_id = p.id;
  IF problem IS NOT NULL THEN RAISE EXCEPTION 'Période déjà taguée, lot refusé : %', problem; END IF;
END $guard$;
-- Classement interne : la date « Modifié » des fiches ne doit pas bouger.
ALTER TABLE public.periods DISABLE TRIGGER trg_periods_updated_at;
UPDATE public.periods AS target SET non_thematic = true
  FROM non_thematic_batch AS batch
  WHERE target.label_fr = batch.label AND target.non_thematic = false;
ALTER TABLE public.periods ENABLE TRIGGER trg_periods_updated_at;
SELECT count(*) AS non_thematic, (SELECT count(*) FROM public.periods) AS periods FROM public.periods WHERE non_thematic;
